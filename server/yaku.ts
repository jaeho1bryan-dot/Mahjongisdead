const winds: Record<string, string> = { 東: '동', 南: '남', 西: '서', 北: '북' }

export function translateYaku(name: string): string {
  const wind = /^(場風|自風) ([東南西北])$/.exec(name)
  if (wind) return `${wind[1] === '場風' ? '장풍패' : '자풍패'} · ${winds[wind[2]]}`
  return yakuNames[name] ?? name
}
